// Local, sanitized UI verification. Never contacts Google Sheets or Discord.
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const express = require('express');
const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright');

(async () => {
  const app = express(), submissions = [], errors = [];
  app.use(express.json());
  app.use(express.static(path.join(__dirname, '../public/public')));
  app.get('/attendance-api/employees', (_req, res) => res.json({ employees: [{ id:'test-one', name:'Test Employee' }, { id:'test-two', name:'Second Employee' }] }));
  app.post('/attendance-api/requests', (req, res) => {
    submissions.push(req.body);
    if (submissions.length === 1) return res.status(400).json({ error:'Select an employee from the current employee list' });
    if (submissions.length === 2) return res.status(503).json({ error:'Could not save your request to Google Sheets. Please retry.' });
    res.status(201).json({ record:{ ...req.body, reference:'REQ-TEST', employeeName:'Test Employee', submittedAt:'2026-10-14T16:41:00Z' }, notificationPending:true });
  });
  const server = app.listen(0, '127.0.0.1');
  await new Promise(resolve => server.once('listening', resolve));
  let browser;
  try {
    browser = await chromium.launch({ headless:true, ...(process.platform === 'win32' ? { channel:'msedge' } : {}) });
    const page = await browser.newPage({ viewport:{ width:390, height:844 }, isMobile:true, deviceScaleFactor:1, reducedMotion:'reduce' });
    page.on('pageerror', error => errors.push(error.message));
    const out = path.resolve(process.env.ATTENDANCE_QA_DIR || path.join(__dirname, '../output/attendance-ui'));
    fs.mkdirSync(out, { recursive:true });
    await page.goto(`http://127.0.0.1:${server.address().port}/request.html`);
    await page.locator('#employee:not([disabled])').waitFor({ state:'attached' });
    assert.equal(await page.locator('.brand').textContent(), 'EMPLOYEE SERVICES');
    assert.equal(await page.locator('.brand-mark').count(), 0);
    const outagePage=await browser.newPage({viewport:{width:390,height:844}});
    await outagePage.route('**/attendance-api/employees',route=>route.fulfill({status:502,contentType:'text/html',body:'<h1>Bad Gateway</h1>'}));
    await outagePage.goto(`http://127.0.0.1:${server.address().port}/request.html`);
    await outagePage.locator('#status').filter({hasText:'temporarily unavailable'}).waitFor();
    await outagePage.click('[data-type=late]');
    assert.equal(await outagePage.locator('#continue').isDisabled(),true);
    await outagePage.unroute('**/attendance-api/employees');
    await outagePage.click('#retry-employees');
    await outagePage.locator('#employee:not([disabled])').waitFor();
    assert.equal(await outagePage.locator('#employee option').nth(1).textContent(),'Test Employee');
    await outagePage.close();
    for (const img of await page.locator('.illustration img').all()) assert.equal(await img.evaluate(e => e.complete && e.naturalWidth > 100), true);
    await page.screenshot({ path:path.join(out, 'mobile-home.png'), fullPage:true });
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
    await page.click('[data-type=late]');
    await page.selectOption('#employee', 'test-one');
    await page.fill('#date', '2026-10-14');
    assert.equal(await page.locator('#scheduled-start').count(), 0);
    assert.equal(await page.locator('#reason-label').textContent(), 'Why?');
    await page.click('#continue');
    assert.equal(await page.locator('#details').isVisible(), true);
    assert.equal(submissions.length, 0);
    await page.fill('#reason', '   ');
    await page.click('#continue');
    assert.equal(await page.locator('#details').isVisible(), true);
    await page.fill('#arrival', '10:15');
    assert.equal(await page.locator('#time-display').textContent(), '10:15 AM');
    assert.equal(await page.locator('.card-arrow svg').count(), 2);
    await page.screenshot({ path:path.join(out, 'mobile-details.png'), fullPage:true });
    await page.fill('#reason', 'Traffic');
    await page.click('#continue');
    await page.fill('#note', 'Test note');
    await page.screenshot({ path:path.join(out, 'mobile-review.png'), fullPage:true });
    await page.click('#submit');
    await page.locator('#sending').waitFor({ state:'hidden' });
    assert.match(await page.locator('#status').textContent(), /Select an employee/);
    assert.equal(await page.locator('#note').isEnabled(), true);
    await page.click('#back');
    assert.equal(await page.locator('#details').isVisible(), true);
    await page.fill('#reason', 'Corrected reason');
    await page.click('#continue');
    await page.click('#submit');
    await page.locator('#sending').waitFor({ state:'hidden' });
    assert.equal(await page.locator('#success').isVisible(), false);
    assert.match(await page.locator('#status').textContent(), /Google Sheets/);
    await page.click('#submit');
    await page.locator('#success').waitFor({ state:'visible' });
    assert.deepEqual(submissions[1], submissions[2], 'ambiguous-save retry must preserve the same request UUID and data');
    assert.equal(submissions[2].reason, 'Corrected reason');
    assert.match(await page.locator('#notification-status').textContent(), /pending/);
    await page.screenshot({ path:path.join(out, 'mobile-success.png'), fullPage:true });
    await page.click('#home');
    await page.locator('#employee:not([disabled])').waitFor({ state:'attached' });
    await page.click('[data-type=sick]');
    await page.selectOption('#employee', 'test-two');
    assert.equal(await page.locator('#late-fields').isVisible(), false);
    assert.equal(await page.locator('#reason-label').textContent(), 'Reason');
    await page.click('#continue');
    assert.equal(await page.locator('#details').isVisible(), true);
    await page.fill('#reason', 'Medical appointment');
    await page.click('#continue');
    assert.match(await page.locator('#review-fields').textContent(), /Second Employee/);
    await page.clock.install();
    let heldRequest;
    await page.route('**/attendance-api/requests', route => { heldRequest = route.request().postDataJSON(); });
    const heldSubmission = page.waitForRequest('**/attendance-api/requests');
    await page.click('#submit');
    await heldSubmission;
    assert.equal(await page.locator('#sending .paper-plane').count(),1);
    await page.screenshot({path:path.join(out,'mobile-submitting.png'),fullPage:true});
    await page.clock.fastForward(30001);
    await page.locator('#sending').waitFor({ state:'hidden' });
    assert.match(await page.locator('#status').textContent(), /took too long/);
    assert.equal(await page.locator('#success').isVisible(), false);
    await page.unroute('**/attendance-api/requests');
    await page.click('#submit');
    await page.locator('#success').waitFor({ state:'visible' });
    assert.deepEqual(submissions.at(-1), heldRequest, 'timeout retry must preserve the same request UUID and data');
    await page.clock.resume();
    await page.click('#home');
    await page.locator('#employee:not([disabled])').waitFor({ state:'attached' });
    await page.click('[data-type=sick]');
    await page.selectOption('#employee', 'test-two');
    await page.fill('#reason', 'Medical appointment');
    await page.click('#continue');
    await page.click('#back'); await page.click('#back');
    await page.setViewportSize({ width:1440, height:1000 });
    await page.screenshot({ path:path.join(out, 'desktop.png'), fullPage:true });
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
    await page.setViewportSize({ width:320, height:740 });
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
    assert.deepEqual(errors, []);
    console.log('PASS: 390/320 mobile and 1440 desktop; artwork; both request types; arrival slider; required reasons; no scheduled start; styled SVG chevrons; editable validation rejection; failed save; timed-out save; stable retries; pending notification receipt; navigation; no page errors.');
  } finally { await browser?.close(); server.close(); }
})().catch(error => { console.error(error); process.exitCode = 1; });
